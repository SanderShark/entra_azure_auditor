# ---- execution ---------------------------------------------------------------------------

def test_dry_run_sends_nothing_and_logs_nothing(tenant, people, groups, tmp_path):
    log = tmp_path / "log.jsonl"
    result = execute_plan(tenant, actions.plan_add_group_members(groups["Finance Share"], [people["alice"]]),
                          dry_run=True, log_path=log)
    assert result.status == "dry_run" and not tenant.writes and not log.exists()


def test_without_a_role_the_result_is_denied_not_failed(tenant, people, groups, tmp_path):
    result = execute_plan(tenant, actions.plan_add_group_members(groups["Finance Share"], [people["alice"]]),
                          actor="me", log_path=tmp_path / "log.jsonl")
    assert result.status == "denied" and result.error.status_code == 403


def test_adding_and_removing_members_is_idempotent(tenant, people, groups, tmp_path):
    with_role(tenant)
    log = tmp_path / "log.jsonl"
    add = actions.plan_add_group_members(groups["Finance Share"], [people["alice"], people["bob"]])
    first = execute_plan(tenant, add, log_path=log)
    assert first.status == "ok" and any("already" in line for line in first.lines)
    assert {"u-alice", "u-bob"} <= tenant.members["g-fin"]
    remove = actions.plan_remove_group_members(groups["Finance Share"], [people["alice"]])
    assert execute_plan(tenant, remove, log_path=log).status == "ok"
    again = execute_plan(tenant, remove, log_path=log)
    assert again.status == "ok" and any("already" in line for line in again.lines)


def test_update_user_is_applied(tenant, people, tmp_path):
    with_role(tenant, "User Administrator")
    plan = actions.plan_update_user(people["alice"], {"jobTitle": "Staff", "department": None},
                                    {"jobTitle": "Engineer", "department": "IT"})
    assert execute_plan(tenant, plan, log_path=tmp_path / "l").status == "ok"
    assert tenant.users["u-alice"]["jobTitle"] == "Staff" and tenant.users["u-alice"]["department"] is None


def test_password_reset_polls_the_operation_and_returns_the_generated_password(tenant, people, tmp_path):
    with_role(tenant, "Helpdesk Administrator")
    result = execute_plan(tenant, actions.plan_reset_password(people["alice"], None),
                          log_path=tmp_path / "l", sleep=lambda s: None)
    assert result.status == "ok" and result.secrets == {"password": "Gen3rated!Pw42"} and tenant.reset_polls >= 2


def test_a_supplied_password_is_sent_but_not_echoed_back(tenant, people, tmp_path):
    with_role(tenant, "Helpdesk Administrator")
    result = execute_plan(tenant, actions.plan_reset_password(people["alice"], "Str0ng!Passw0rd#9"),
                          log_path=tmp_path / "l", sleep=lambda s: None)
    assert result.status == "ok" and "password" not in result.secrets
    assert tenant.writes[-1][2] == {"newPassword": "Str0ng!Passw0rd#9"}


def test_certificate_ids_are_written_and_sessions_revoked(tenant, people, tmp_path):
    with_role(tenant, "Privileged Authentication Administrator")
    new = certids.build_cert_id("ski", "AB:CD")
    plan = actions.plan_set_certificate_user_ids(people["alice"], ["X509:<PN>alice@contoso.com", new], ["X509:<PN>alice@contoso.com"])
    assert execute_plan(tenant, plan, log_path=tmp_path / "l").status == "ok"
    assert tenant.certs["u-alice"][-1] == "X509:<SKI>ABCD"
    assert execute_plan(tenant, actions.plan_revoke_sessions(people["alice"]), log_path=tmp_path / "l").status == "ok"


def test_the_log_records_who_what_and_result_but_never_a_password(tenant, people, groups, tmp_path):
    with_role(tenant, "Helpdesk Administrator")
    tenant.active_roles["r2"] = "Groups Administrator"
    log = tmp_path / "log.jsonl"
    execute_plan(tenant, actions.plan_reset_password(people["alice"], "Str0ng!Passw0rd#9"), actor="me", log_path=log, sleep=lambda s: None)
    execute_plan(tenant, actions.plan_reset_password(people["alice"], None), actor="me", log_path=log, sleep=lambda s: None)
    execute_plan(tenant, actions.plan_add_group_members(groups["Finance Share"], [people["alice"]]), actor="me", log_path=log)
    entries = audit_log.read_recent(10, log)
    assert [e["status"] for e in entries] == ["ok", "ok", "ok"] and entries[0]["actor"] == "me"
    assert entries[2]["target"] == {"type": "group", "id": "g-fin", "name": "Finance Share"}
    text = log.read_text()
    assert "Str0ng" not in text and "Gen3rated" not in text


def test_a_hard_failure_is_reported_as_failed(people, groups, tmp_path):
    class Boom(FakeTenant):
        def request(self, method, path, **kw):
            from entra_auditor.graph.client import GraphError
            raise GraphError("500 server exploded", status_code=500)

    result = execute_plan(Boom(), actions.plan_revoke_sessions(people["alice"]), log_path=tmp_path / "l")
    assert result.status == "failed" and "exploded" in result.message


def test_a_failure_after_the_first_success_is_partial(people, groups, tmp_path):
    class FailsSecond(FakeTenant):
        calls = 0

        def request(self, method, path, **kw):
            FailsSecond.calls += 1
            if FailsSecond.calls == 2:
                from entra_auditor.graph.client import GraphError
                raise GraphError("500", status_code=500)
            return super().request(method, path, **kw)

    FailsSecond.calls = 0
    tenant = with_role(FailsSecond())
    plan = actions.plan_add_group_members(groups["Finance Share"], [people["bob"], people["alice"]])
    assert execute_plan(tenant, plan, log_path=tmp_path / "l").status == "partial"


def test_a_logging_problem_never_turns_success_into_failure(tenant, people, tmp_path):
    with_role(tenant, "User Administrator")
    blocker = tmp_path / "blocked"
    blocker.write_text("a file, so the log directory can't be created")
    plan = actions.plan_set_enabled(people["alice"], False)
    result = execute_plan(tenant, plan, log_path=blocker / "log.jsonl")
    assert result.status == "ok" and any("action log" in line for line in result.lines)
