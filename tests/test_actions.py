import json

import pytest

from entra_auditor.toolkit import actions, audit_log, certids
from entra_auditor.toolkit.actions import PlanError, execute_plan
from entra_auditor.toolkit.search import resolve_group, resolve_user
from tests.fakes import FakeTenant


@pytest.fixture
def people(tenant):
    return {
        "alice": resolve_user(tenant, "alice@contoso.com"),
        "bob": resolve_user(tenant, "bob@contoso.com"),
        "sync": resolve_user(tenant, "sam@contoso.com"),
    }


@pytest.fixture
def groups(tenant):
    return {name: resolve_group(tenant, name) for name in
            ("Finance Share", "Dynamic IT", "Mail-Sec", "AD Group", "Role Group", "Project X")}


def with_role(tenant, name="Groups Administrator"):
    tenant.active_roles["r"] = name
    return tenant


# ---- parse_assignments -------------------------------------------------------------------

def test_assignments_use_aliases_clear_values_and_uppercase_countries():
    changes = actions.parse_assignments(["title=Staff Engineer", "dept=", "Location=us", "first=Alice"])
    assert changes == {"jobTitle": "Staff Engineer", "department": None, "usageLocation": "US", "givenName": "Alice"}


@pytest.mark.parametrize("items,message", [
    (["salary=1"], "can't be edited"), (["title"], "field=value"), (["location=USA"], "two-letter"),
    (["name="], "empty"), ([], "Nothing"), (["title=a\x01b"], "control"), (["title=" + "x" * 300], "too long"),
])
def test_bad_assignments_are_refused(items, message):
    with pytest.raises(PlanError, match=message):
        actions.parse_assignments(items)


# ---- user plans --------------------------------------------------------------------------

def test_update_plan_shows_old_and_new_values(people):
    plan = actions.plan_update_user(people["alice"], {"jobTitle": "Staff", "department": None},
                                    {"jobTitle": "Engineer", "department": "IT"})
    assert plan.details == ["jobTitle: 'Engineer' -> 'Staff'", "department: 'IT' -> (empty)"]
    assert plan.requests[0].method == "PATCH" and plan.suggested_roles == ("User Administrator",)


